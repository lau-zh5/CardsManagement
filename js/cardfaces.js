function hash(s) { let h = 2166136261; for (let i = 0; i < s.length; i++) h = Math.imul(h ^ s.charCodeAt(i), 16777619); return h >>> 0; }

export function matchBank(text) {
  const q = String(text || "").toLowerCase().replace(/\s+/g, "");
  if (!q) return null;
  let best = null, bestLen = 0;
  for (const [key, b] of Object.entries(BANK_FACES)) {
    for (const a of b.alias) {
      const al = a.toLowerCase();
      if (q.includes(al) && al.length > bestLen) { best = key; bestLen = al.length; }
    }
  }
  return best;
}

export function faceInfoFor(card) {
  if (card.faceStyle === "solid") return null;
  const key = matchBank(card.issuer || card.values?.bank || card.nickname || "");
  if (!key) return null;
  const b = BANK_FACES[key];
  const imgs = b.images;
  if (!imgs || !imgs.length) return null;
  const i = hash(String(card.id || "") + String(card.nickname || "")) % imgs.length;
  return {
    image: imgs[i],
    bank: b.name,
    short: b.short,
    cardName: String(b.source[i] || "").replace(/\.(png|jpe?g|webp)$/i, ""),
    key
  };
}

export function faceImageFor(card) {
  const info = faceInfoFor(card);
  return info ? info.image : null;
}
